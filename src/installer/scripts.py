"""Generate executable scripts, on various platforms."""

import io
import os
import shlex
import zipfile
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from importlib.resources import files
from typing import TYPE_CHECKING

from installer import _scripts

if TYPE_CHECKING:
    from typing import Literal

    LauncherKind = Literal["posix", "win-ia32", "win-amd64", "win-arm", "win-arm64"]
    ScriptSection = Literal["console", "gui"]


__all__ = ["InvalidScript", "Script"]


# These characters can never be safely embedded in a shebang line or a
# single-line ``/bin/sh`` ``exec`` command, so they are rejected outright.
_FORBIDDEN_INTERPRETER_CHARS = ("\x00", "\r", "\n")


_ALLOWED_LAUNCHERS: Mapping[tuple["ScriptSection", "LauncherKind"], str] = {
    ("console", "win-ia32"): "t32.exe",
    ("console", "win-amd64"): "t64.exe",
    ("console", "win-arm"): "t_arm.exe",
    ("console", "win-arm64"): "t64-arm.exe",
    ("gui", "win-ia32"): "w32.exe",
    ("gui", "win-amd64"): "w64.exe",
    ("gui", "win-arm"): "w_arm.exe",
    ("gui", "win-arm64"): "w64-arm.exe",
}

_SCRIPT_TEMPLATE = """\
# -*- coding: utf-8 -*-
import re
import sys
from {module} import {import_name}
if __name__ == "__main__":
    sys.argv[0] = re.sub(r"(-script\\.pyw|\\.exe)?$", "", sys.argv[0])
    sys.exit({func_path}())
"""


class InvalidScript(ValueError):
    """Raised if the user provides incorrect script section or kind."""


def validate_interpreter(
    executable: str,
    interpreter_args: Sequence[str] = (),
    *,
    for_launcher: bool = False,
) -> None:
    """Validate an interpreter invocation, before any script bytes are generated.

    :param executable: Path to the executable to invoke.
    :param interpreter_args: Arguments to pass to the executable, before the
        generated script and the user's arguments.
    :param for_launcher: Whether the invocation is meant to be embedded in a
        Windows launcher (instead of a POSIX script).

    :raises InvalidScript: if any value contains a NUL/CR/LF character, or if
        interpreter arguments are requested for a Windows launcher.
    """
    if for_launcher:
        # The Windows launchers embed the executable line verbatim (legacy
        # callers even pass the complete ``#!...`` line, including its
        # trailing newline) and cannot express separate interpreter
        # arguments, so the POSIX-only guarantees do not apply here. The one
        # thing we do is refuse arguments, rather than silently mangling them
        # into a path the launcher would not understand.
        if interpreter_args:
            raise InvalidScript(
                "Interpreter arguments are only supported with the 'posix' "
                "launcher, since the Windows launchers do not understand "
                "arguments embedded in the executable path."
            )
        return

    values: list[tuple[str, str]] = [("executable", executable)]
    values.extend(
        (f"argument {index}", arg) for index, arg in enumerate(interpreter_args)
    )
    for label, value in values:
        for char in _FORBIDDEN_INTERPRETER_CHARS:
            if char in value:
                raise InvalidScript(
                    f"Interpreter {label} {value!r} contains a forbidden "
                    f"character: {char!r}"
                )


def build_posix_wrapper(executable: str, interpreter_args: Sequence[str] = ()) -> bytes:
    r"""Build a POSIX ``/bin/sh`` + Python polyglot wrapper.

    The generated bytes are valid both as a ``/bin/sh`` script and as Python
    source. When executed by a shell, the second line uses ``exec`` to run the
    interpreter (replacing the shell process, so exit codes and signals are
    handled by the interpreter directly), passing the interpreter arguments
    first, followed by the script path (``"$0"``) and the caller's arguments
    (``"$@"``). When read by Python, the shell line is a discarded
    triple-quoted expression statement.

    Every interpreter-side token is quoted with :func:`shlex.quote`, so its
    byte boundaries are preserved exactly and no shell expansion (quotes,
    ``$()``, backticks, ...) can take place.

    The returned bytes do not end with a newline; callers append one before
    the Python script body.

    :param executable: Path to the executable to invoke.
    :param interpreter_args: Arguments to pass to the executable, before the
        generated script and the user's arguments.
    """
    quoted_tokens = [shlex.quote(executable)]
    quoted_tokens.extend(shlex.quote(arg) for arg in interpreter_args)
    command = " ".join(quoted_tokens).encode("utf-8")
    return b"#!/bin/sh\n'''exec' " + command + b" \"$0\" \"$@\"\n' '''"


@dataclass
class Script:
    """Describes a script based on an entry point declaration."""

    name: str
    """Name of the script."""

    module: str
    """Module path, to load the entry point from."""

    attr: str
    """Final attribute access, for the entry point."""

    section: "ScriptSection" = field(repr=False)
    """
    Denotes the "entry point section" where this was specified. Valid values
    are ``"gui"`` and ``"console"``.
    """

    def _get_launcher_data(self, kind: "LauncherKind") -> bytes | None:
        if kind == "posix":
            return None
        key = (self.section, kind)
        try:
            name = _ALLOWED_LAUNCHERS[key]
        except KeyError:
            error = f"{key!r} not in {sorted(_ALLOWED_LAUNCHERS)!r}"
            raise InvalidScript(error) from None
        return (files(_scripts) / name).read_bytes()

    def _get_alternate_executable(self, executable: str, kind: "LauncherKind") -> str:
        """Get an alternate executable for the launcher.

        On Windows, when the script section is gui-script, pythonw.exe should be used.
        """
        if self.section == "gui" and kind != "posix":
            dn, fn = os.path.split(executable)
            fn = fn.replace("python", "pythonw")
            executable = os.path.join(dn, fn)  # noqa: PTH118
        return executable

    def generate(
        self,
        executable: str,
        kind: "LauncherKind",
        interpreter_args: Sequence[str] = (),
    ) -> tuple[str, bytes]:
        """Generate a launcher for this script.

        :param executable: Path to the executable to invoke.
        :param kind: Which launcher template should be used.
            Valid values are ``"posix"``, ``"win-ia32"``, ``"win-amd64"`` and
            ``"win-arm"``.
        :type kind: str
        :param interpreter_args: Exact arguments to invoke the executable
            with, placed before the generated script and the caller's
            arguments. Each item is passed as a separate, literal argv entry
            (empty strings and quotes are preserved); they are never joined
            into one string or re-split by a shell. Only supported with the
            ``"posix"`` kind.

        :raises InvalidScript: if no appropriate template is available, if
            ``executable``/``interpreter_args`` contain NUL/CR/LF, or if
            interpreter arguments are requested with a Windows launcher.
        :return: The name and contents of the launcher file.
        """
        interpreter_args = tuple(interpreter_args)
        launcher = self._get_launcher_data(kind)
        validate_interpreter(
            executable, interpreter_args, for_launcher=launcher is not None
        )
        executable = self._get_alternate_executable(executable, kind)
        shebang = self._build_shebang(
            executable,
            forlauncher=launcher is not None,
            interpreter_args=interpreter_args,
        )
        code = _SCRIPT_TEMPLATE.format(
            module=self.module,
            import_name=self.attr.split(".")[0],
            func_path=self.attr,
        ).encode("utf-8")

        if launcher is None:
            return self.name, shebang + b"\n" + code

        stream = io.BytesIO()
        with zipfile.ZipFile(stream, "w") as zf:
            zf.writestr("__main__.py", code)
        name = f"{self.name}.exe"
        data = launcher + shebang + b"\n" + stream.getvalue()
        return name, data

    @staticmethod
    def _is_executable_simple(executable: bytes) -> bool:
        if b" " in executable:
            return False
        shebang_length = len(executable) + 3  # Prefix #! and newline after.
        # According to distlib, Darwin can handle up to 512 characters. But I want
        # to avoid platform sniffing to make this as platform-agnostic as possible.
        # The "complex" script isn't that bad anyway.
        return shebang_length <= 127

    def _build_shebang(
        self,
        executable: str,
        forlauncher: bool,
        interpreter_args: Sequence[str] = (),
    ) -> bytes:
        """Build a shebang line.

        The non-launcher cases are taken directly from distlib's implementation,
        which tries its best to account for command length, spaces in path, etc.

        https://bitbucket.org/pypa/distlib/src/58cd5c6/distlib/scripts.py#lines-124

        When ``interpreter_args`` are given, the POSIX ``/bin/sh`` polyglot
        wrapper is always used -- kernel support for multiple shebang
        arguments is inconsistent, and the wrapper guarantees exact argv
        boundaries.
        """
        executable_bytes = executable.encode("utf-8")
        if forlauncher:  # The launcher can just use the command as-is.
            return b"#!" + executable_bytes
        if not interpreter_args and self._is_executable_simple(executable_bytes):
            return b"#!" + executable_bytes

        # Shebang support for an executable with a space in it (or for extra
        # interpreter arguments) is under-specified and platform-dependent, so
        # we use a clever hack to generate a script to run in ``/bin/sh`` that
        # should work on all reasonably modern platforms.
        # Read the following message to understand how the hack works:
        # https://github.com/pypa/installer/pull/4#issuecomment-623668717

        # I don't understand a lick what this is trying to do.
        return build_posix_wrapper(executable, interpreter_args)
